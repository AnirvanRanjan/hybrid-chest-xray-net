"""
05_view_check.py  —  post-hoc check on one subgroup finding: is the lower cardiomegaly
sensitivity in patients aged 60+ explained by acquisition (AP vs PA films)?

Reads pred_test.csv and thresholds_val.npy of one run and writes LaTeX macros
(\\resdef{<tag>.test.view.<name>}{value}) with, for one class: the AP share of all images
and of positive images per age group, and the sensitivity at the validation threshold per
age group within AP and within PA films. Descriptive counts only; no thresholds or models
are chosen here.

  python 05_view_check.py --run_dir results/hyb_320 --tag E --out ../paper/generated/E
"""
import argparse
import os

import numpy as np
import pandas as pd

AGE_BINS = [(0, 40, "lt40"), (40, 60, "40to59"), (60, 101, "60plus")]

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--run_dir", required=True)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--cls", default="Cardiomegaly")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    d = pd.read_csv(os.path.join(a.run_dir, "pred_test.csv"))
    classes = [c[2:] for c in d.columns if c.startswith("y_")]
    t = float(np.load(os.path.join(a.run_dir, "thresholds_val.npy"))[classes.index(a.cls)])
    y, pred = d[f"y_{a.cls}"] == 1, d[f"p_{a.cls}"] >= t
    ap_view = d["View Position"] == "AP"

    vals = {"cls": a.cls, "thr": f"{t:.2f}"}

    def pct(x):
        return f"{100 * x:.0f}\\%"

    def tpr(mask):
        m = mask & y
        return pct(pred[m].mean()) if m.sum() else "--", int(m.sum())

    for view, vm in (("AP", ap_view), ("PA", ~ap_view)):
        vals[f"tpr.{view}"], vals[f"npos.{view}"] = tpr(vm)
    for lo, hi, key in AGE_BINS:
        g = (d.age_clean >= lo) & (d.age_clean < hi)
        vals[f"apshare.{key}"] = pct(ap_view[g].mean())
        vals[f"apshare_pos.{key}"] = pct(ap_view[g & y].mean())
        for view, vm in (("AP", ap_view), ("PA", ~ap_view)):
            vals[f"tpr.{key}.{view}"], vals[f"npos.{key}.{view}"] = tpr(g & vm)

    os.makedirs(a.out, exist_ok=True)
    path = os.path.join(a.out, "test_view_results.tex")
    with open(path, "w") as f:
        f.write(f"% generated by 05_view_check.py from {os.path.basename(a.run_dir)}/pred_test.csv -- do not edit by hand\n")
        for k, v in vals.items():
            f.write(f"\\resdef{{{a.tag}.test.view.{k}}}{{{v}}}\n")
    print(open(path).read())
